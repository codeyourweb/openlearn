export const dictionaries = { en, fr, it, es, de, ru, zh, ja, pt, hi, bn, ar };

function readStoredLanguage() {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored && LANGUAGES.some((item) => item.code === stored)) return stored;
  } catch {
    /* storage can be disabled */
  }
  const browser = (navigator.language || "").slice(0, 2).toLowerCase();
  return LANGUAGES.some((item) => item.code === browser) ? browser : DEFAULT_LANGUAGE;
}

export const i18n = {
  language: readStoredLanguage(),
  listeners: [],
};

// Applied before the first render: an Arabic reader gets the document flipped
// without watching the page turn around once.
document.documentElement.lang = i18n.language;
document.documentElement.dir = isRtl(i18n.language) ? "rtl" : "ltr";

export function currentLanguage() {
  return i18n.language;
}

export function setLanguage(code) {
  if (!LANGUAGES.some((item) => item.code === code)) return;
  i18n.language = code;
  try {
    localStorage.setItem(STORAGE_KEY, code);
  } catch {
    /* ignore */
  }
  document.documentElement.lang = code;
  document.documentElement.dir = isRtl(code) ? "rtl" : "ltr";
  i18n.listeners.forEach((listener) => listener(code));
}

export function onLanguageChange(listener) {
  i18n.listeners.push(listener);
}

/** The wording a reader of the current language should see.
 *
 * A questionnaire carries its translations beside its authored text, which is
 * written in the quiz's default language: showing that text when the asked-for
 * language is missing is what keeps a half-translated quiz readable — and lets
 * a player switch language in the middle of a run without starting it again.
 */
export function localized(original, translations) {
  const text = (translations || {})[currentLanguage()];
  return text || original || "";
}

/** Translate a key, interpolating `{name}` placeholders. */
export function t(key, params = {}) {
  const dict = dictionaries[i18n.language] || en;
  const template = dict[key] ?? en[key] ?? key;
  return String(template).replace(/\{(\w+)\}/g, (match, name) => (name in params ? params[name] : match));
}

/** Singular/plural pick for a count, using two dedicated keys. */
export function tp(oneKey, manyKey, count, params = {}) {
  return t(count === 1 ? oneKey : manyKey, { n: count, ...params });
}

/** Localised label for a quiz status. */
export function statusLabel(status) {
  return t(`dash.status.${status}`) === `dash.status.${status}` ? status : t(`dash.status.${status}`);
}

export function languageLabel(code) {
  return (LANGUAGES.find((item) => item.code === code) || {}).label || code;
}
